import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';
import { isPart, learnParts, type LearnPage, type LearnPart } from './src/map';

type SidebarItem = Extract<SidebarsConfig[string], unknown[]>[number];

function itemsOf(part: LearnPart): SidebarItem[] {
  if (part.parts !== undefined) {
    return part.parts.map(sidebarItemOf);
  }
  if (part.directory === undefined) {
    throw new Error(`The part ${part.label} has no pages`);
  }
  return [{ type: 'autogenerated', dirName: part.directory }];
}

function sidebarItemOf(part: LearnPart | LearnPage): SidebarItem {
  if (!isPart(part)) {
    return { type: 'doc', id: part.doc };
  }
  return {
    type: 'category',
    label: part.label,
    link: 'doc' in part.opening
      ? { type: 'doc', id: part.opening.doc }
      : { type: 'generated-index', slug: part.opening.index, description: part.opening.description },
    items: itemsOf(part),
  };
}

export default {
  learnSidebar: learnParts.map(sidebarItemOf),
  developSidebar: [{ type: 'autogenerated', dirName: 'develop' }],
} satisfies SidebarsConfig;
