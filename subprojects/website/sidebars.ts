import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';
import { learnParts, type LearnPart } from './src/map';

type SidebarItem = Extract<SidebarsConfig[string], unknown[]>[number];

function sidebarItemOf(part: LearnPart): SidebarItem {
  const customProps = { description: part.description };
  if (part.directory === undefined) {
    if (!('doc' in part.opening)) {
      throw new Error(`The part ${part.label} has no pages`);
    }
    return { type: 'doc', id: part.opening.doc, label: part.label, customProps };
  }
  return {
    type: 'category',
    label: part.label,
    link: 'doc' in part.opening
      ? { type: 'doc', id: part.opening.doc }
      : { type: 'generated-index', slug: part.opening.index, description: part.description },
    customProps,
    items: [{ type: 'autogenerated', dirName: part.directory }],
  };
}

export default {
  learnSidebar: [
    'learn/index',
    ...learnParts.map(sidebarItemOf),
  ],
  developSidebar: [{ type: 'autogenerated', dirName: 'develop' }],
} satisfies SidebarsConfig;
